//! minicoin — минимальная, но настоящая криптовалюта.
//!
//! Модули расположены в порядке чтения: каждый опирается только на
//! предыдущие. Если читать сверху вниз, получится учебник.
//!
//! 1. `crypto`    — хеш и подписи (единственное, что взято из библиотек)
//! 2. `codec`     — как числа и массивы превращаются в байты
//! 3. `address`   — человекочитаемый адрес `mc1…` (Bech32m)
//! 4. `tx`        — транзакция: входы, выходы, подпись
//! 5. `block`     — блок, дерево Меркла, доказательство работы
//! 6. `consensus` — параметры сети и правила, не зависящие от истории
//! 7. `chain`     — цепочка, набор UTXO, откат и реорганизация
//! 8. `mempool`   — очередь неподтверждённых транзакций
//! 9. `net`       — сообщения сетевого протокола
//! 10. `node`     — узел: соединения, синхронизация, майнер
//! 11. `wallet`   — ключ, баланс, сборка платежа
//! 12. `explain`  — побайтовый разбор блока для людей

pub mod address;
pub mod block;
pub mod chain;
pub mod codec;
pub mod consensus;
pub mod crypto;
pub mod explain;
pub mod mempool;
pub mod net;
pub mod node;
pub mod tx;
pub mod wallet;
